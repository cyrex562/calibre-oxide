//! A narrow port of `old_src/src/calibre/customize/profiles.py`'s
//! `output_profiles` list -- **not** the full `Plugin`/`OutputProfile`
//! class hierarchy (which carries many more fields for other features:
//! `screen_size`, `comic_screen_size`, `touchscreen`, CSS module support,
//! etc.), just the four fields `epub_mobi_builder.py`'s `CatalogBuilder`
//! actually reads from a resolved profile: `short_name`, `dpi`,
//! `ratings_char`, `empty_ratings_char`.
//!
//! This unblocks two previously-deferred pieces of the `epub_mobi_builder.py`
//! port (issue #57): `get_output_profile` itself, and
//! `calculate_thumbnail_dimensions` (cluster E), which needs a profile's
//! real `dpi`. It's the same data source `generate_rating_string`'s
//! `full_char`/`empty_char` parameters (already threaded through every
//! HTML/NCX generator in clusters B-D) were always meant to be resolved
//! from -- those callers now have a real place to get them from, once
//! cluster F wires everything together.
//!
//! # How this table was generated
//!
//! Every upstream `*Output` class inherits some fields and overrides
//! others; hand-tracing 39 classes' inheritance chains by eye risks
//! transcription errors. Instead, this table was generated by actually
//! importing `profiles.py` (with `calibre`/`calibre.customize` stubbed to
//! satisfy its one real import) and reading each of `output_profiles`'
//! *resolved* `short_name`/`dpi`/`ratings_char`/`empty_ratings_char`
//! values directly off the live Python classes -- letting Python's own
//! MRO do the inheritance resolution rather than re-deriving it by hand,
//! matching the same "codegen from the live source, not a hand trace"
//! technique used for issue #55's `unihandecode` data tables.

