/// Port of `CatalogBuilder.get_output_profile`: the profile matching
/// `short_name`, or `None` if none does (matching upstream's own `for`
/// loop falling through with no `break`).
pub fn get_output_profile(short_name: &str) -> Option<&'static OutputProfile> {
    OUTPUT_PROFILES.iter().find(|p| p.short_name == short_name)
}

/// Port of `calculate_thumbnail_dimensions`. Returns `(0.0, 0.0)` when
/// `output_profile` doesn't match any known profile, matching upstream's
/// own behavior of leaving `self.thumb_width`/`self.thumb_height` at
/// their `__init__` defaults (`0`) when the loop never matches.
pub fn calculate_thumbnail_dimensions(output_profile: &str, thumb_width_inches: f64, fmt: &str) -> (f64, f64) {
    let Some(profile) = get_output_profile(output_profile) else {
        return (0.0, 0.0);
    };
    let mut width = profile.dpi * thumb_width_inches;
    let mut height = width * 1.33;
    if profile.short_name.contains("kindle") && fmt == "mobi" {
        // Python's `//` on floats floors; not simple truncation for
        // already-non-negative values, but they're equivalent here.
        width = (width / 2.0).floor();
        height = (height / 2.0).floor();
    }
    (width, height)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_has_every_profile_and_no_duplicates() {
        assert_eq!(OUTPUT_PROFILES.len(), 40);
        let mut names: Vec<&str> = OUTPUT_PROFILES.iter().map(|p| p.short_name).collect();
        names.sort();
        names.dedup();
        assert_eq!(names.len(), 40);
    }

    #[test]
    fn get_output_profile_finds_a_known_profile() {
        let p = get_output_profile("kindle").unwrap();
        assert_eq!(p.dpi, 168.451);
        assert_eq!(p.ratings_char, "\u{2605}");
    }

    #[test]
    fn get_output_profile_none_for_unknown_short_name() {
        assert!(get_output_profile("not_a_real_device").is_none());
    }

    #[test]
    fn default_profile_uses_ascii_rating_glyphs() {
        let p = get_output_profile("default").unwrap();
        assert_eq!(p.ratings_char, "*");
        assert_eq!(p.empty_ratings_char, " ");
    }

    #[test]
    fn calculate_thumbnail_dimensions_scales_by_dpi() {
        let (w, h) = calculate_thumbnail_dimensions("default", 1.0, "epub");
        assert_eq!(w, 100.0);
        assert_eq!(h, 133.0);
    }

    #[test]
    fn calculate_thumbnail_dimensions_halves_for_kindle_mobi() {
        // kindle dpi=168.451; width = 168.451*1.0 = 168.451, height =
        // 168.451*1.33 = 224.03983; both halved+floored for kindle+mobi.
        let (w, h) = calculate_thumbnail_dimensions("kindle", 1.0, "mobi");
        assert_eq!(w, 84.0);
        assert_eq!(h, 112.0);
    }

    #[test]
    fn calculate_thumbnail_dimensions_does_not_halve_kindle_epub() {
        // No halving (and no flooring at all) for non-"mobi" formats --
        // width is exactly dpi * thumb_width_inches, unrounded.
        let (w, _h) = calculate_thumbnail_dimensions("kindle", 1.0, "epub");
        assert_eq!(w, 168.451);
    }

    #[test]
    fn calculate_thumbnail_dimensions_zero_for_unknown_profile() {
        assert_eq!(calculate_thumbnail_dimensions("not_a_real_device", 1.0, "epub"), (0.0, 0.0));
    }
}
